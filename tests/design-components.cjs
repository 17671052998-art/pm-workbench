const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const { unzipSync, strFromU8 } = require("fflate");

module.exports = async function testComponents() {
  const { createGraph, addNode, solid, color, vectorProps, stats, EMPTY_PNG } = await import("../src/design/common.mjs");
  const { readDesign, convertDesign, inspectDesign } = await import("../src/design/convert.mjs");
  const graph = createGraph(), page = graph.addPage("Components");
  const component = addNode(graph, "COMPONENT", page.id, { name: "Editable master", x: 30, y: 40, width: 100, height: 100 });
  addNode(graph, "VECTOR", component.id, { name: "Triangle", width: 100, height: 100, fills: [solid(color(1, 0, 0))], ...vectorProps("M0 0 L100 100 L0 100 Z") });
  const parsed = { graph, source: "fig", filename: "component.fig", thumbnail: EMPTY_PNG, issues: [], stats: stats(graph) };
  const before = structuredClone([...graph.nodes.values()]);
  assert.equal(inspectDesign(parsed, "xd").some((issue) => issue.code === "component-expanded"), false);
  const result = await convertDesign(parsed, "xd");
  assert.deepEqual([...graph.nodes.values()], before);
  const archive = unzipSync(result.bytes);
  const global = JSON.parse(strFromU8(archive["resources/graphics/graphicContent.agc"]));
  const symbols = global.resources.meta.ux.symbols;
  assert.equal(symbols.length, 1);
  const board = Object.entries(archive).filter(([name]) => name.startsWith("artwork/artboard-") && name.endsWith(".agc")).map(([,bytes]) => JSON.parse(strFromU8(bytes)))[0].children[0];
  assert.equal(board.meta.ux.orbitComponentCanvas, true);
  const master = board.artboard.children[0];
  assert.equal(master.meta.ux.isMaster, true);
  assert.equal(master.meta.ux.symbolId, symbols[0].meta.ux.symbolId);
  assert.equal(master.group.children[0].syncSourceGuid, symbols[0].group.children[0].id);
  assert.equal(master.meta.ux.syncMap[symbols[0].group.children[0].id], master.group.children[0].guid);
  const output = await readDesign(result.bytes, result.filename);
  assert.equal(output.issues.some((issue) => issue.code === "xd-component"), false);
  const restored = [...output.graph.nodes.values()].find((node) => node.name === component.name);
  assert.equal(restored.type, "COMPONENT");
  assert.equal(output.graph.getNode(restored.parentId).type, "CANVAS");
  assert.deepEqual([restored.x, restored.y, restored.width, restored.height], [30, 40, 100, 100]);
  assert.equal(output.graph.getChildren(restored.id)[0].name, "Triangle");
  const instance = addNode(graph, "INSTANCE", page.id, { name: "Existing source instance", componentId: component.id });
  assert.ok(inspectDesign(parsed, "xd").some((issue) => issue.code === "component-expanded"));
  graph.deleteNode(instance.id);
  await fs.writeFile("/tmp/pm-workbench-component.xd", result.bytes);
  console.log("PASS: standalone components retain a native XD master definition, synchronization IDs and editable vectors; unsupported existing instance relations remain explicit.");
};
