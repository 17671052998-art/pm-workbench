const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const { unzipSync, strFromU8 } = require("fflate");

module.exports = async function testCompatible() {
  const { createGraph, addNode, addImage, color, solid, vectorProps, stats, EMPTY_PNG } = await import("../src/design/common.mjs");
  const { canvasSurface, decodeImage } = await import("../src/design/canvas-node.mjs");
  const { readDesign, inspectDesign, convertDesign } = await import("../src/design/convert.mjs");
  const { writeFigma } = await import("../src/design/figma.mjs");
  const { prepareXDCompatibility } = await import("../src/design/xd-compat.mjs");
  const graph = createGraph(), page = graph.addPage("Compatibility");
  const board = addNode(graph, "FRAME", page.id, { name: "Compatibility Board", width: 300, height: 160, fills: [solid(color(1, 1, 1))] });
  const pixels = canvasSurface(16, 16); pixels.ctx.fillStyle = "rgba(100,150,200,0.5)"; pixels.ctx.fillRect(0, 0, 16, 16);
  const hash = await addImage(graph, await pixels.png());
  const group = addNode(graph, "GROUP", board.id, { name: "Fade", x: 20, y: 20, width: 16, height: 16 });
  const gradient = { ...solid(color()), type: "GRADIENT_LINEAR", gradientTransform: { m00: 0, m01: 1, m02: 0, m10: -1, m11: 0, m12: 1 }, gradientStops: [{ position: 0, color: color(1, 1, 1, 1) }, { position: 1, color: color(1, 1, 1, 0) }] };
  const mask = addNode(graph, "VECTOR", group.id, { name: "Gradient mask", width: 16, height: 16, isMask: true, maskType: "ALPHA", fills: [gradient], ...vectorProps("M0 0 L16 0 L16 -16 L0 -16 Z") });
  mask.source.format = "fig";
  const image = addNode(graph, "RECTANGLE", group.id, { name: "Original image", width: 16, height: 16, fills: [{ ...solid(color(), 0.6), type: "IMAGE", imageHash: hash, imageScaleMode: "FILL", blendMode: "SOFT_LIGHT" }] });
  const shadow = addNode(graph, "ROUNDED_RECTANGLE", board.id, { name: "Spread shadow", x: 70, y: 20, width: 120, height: 60, cornerRadius: 12, fills: [solid(color(0.4, 0.1, 0.1))], effects: [{ type: "INNER_SHADOW", color: color(1, 0.9, 0.9, 0.5), offset: { x: 0, y: 1 }, radius: 10, spread: 5, visible: true, blendMode: "NORMAL" }] });
  const glyph = vectorProps("M0 -1 L0.5 -1 L0.5 0 L0 0 Z").fillGeometry[0].commandsBlob;
  const text = addNode(graph, "TEXT", board.id, { name: "Gradient text", x: 20, y: 90, width: 40, height: 25, fontSize: 20, fontFamily: "Arial", text: "X", fills: [{ ...gradient, gradientStops: [{ position: 0, color: color(1, 0, 0) }, { position: 1, color: color(0, 0, 1) }] }], derivedTextGlyphs: [{ x: 0, y: 20, fontSize: 20, commandsBlob: Uint8Array.of(0, ...glyph) }] });
  const parsed = { graph, source: "fig", filename: "compatible.fig", thumbnail: EMPTY_PNG, stats: stats(graph), issues: [] };
  const before = structuredClone([...graph.nodes.values()]), originalImages = [...graph.images];
  await assert.rejects(convertDesign(parsed, "xd"), (error) => error.code === "PRESERVATION_REQUIRED");
  const options = { mode: "compatible" };
  const issues = inspectDesign(parsed, "xd", options);
  assert.equal(issues.filter((issue) => issue.category === "compatibility").length, 3);
  assert.ok(issues.every((issue) => issue.severity === "info"));
  const prepared = await prepareXDCompatibility(graph);
  const decoded = await decodeImage(prepared.resources.get(prepared.images.get(image.id)));
  const outputPixels = canvasSurface(16, 16); outputPixels.ctx.drawImage(decoded, 0, 0);
  const alpha = (x, y) => outputPixels.ctx.getImageData(x, y, 1, 1).data[3];
  assert.ok(Math.abs(alpha(8, 0) - 124) <= 1);
  assert.ok(Math.abs(alpha(8, 8) - 60) <= 1);
  assert.ok(Math.abs(alpha(8, 15) - 4) <= 1);
  const shadowResource = await decodeImage(prepared.resources.get(prepared.shadows.get(shadow.id)[0].hash));
  const shadowPixels = canvasSurface(shadowResource.width, shadowResource.height); shadowPixels.ctx.drawImage(shadowResource, 0, 0);
  assert.equal(shadowPixels.ctx.getImageData(0, 0, 1, 1).data[3], 0, "rounded corners remain transparent");
  assert.ok(shadowPixels.ctx.getImageData(180, 4, 1, 1).data[3] > 70, "spread increases the inner edge shadow");
  assert.ok(shadowPixels.ctx.getImageData(180, 90, 1, 1).data[3] < 5, "center is not flattened over the native fill");
  const result = await convertDesign(parsed, "xd", options);
  assert.equal(result.mode, "compatible");
  assert.deepEqual([...graph.nodes.values()], before);
  assert.deepEqual([...graph.images], originalImages);
  const archive = unzipSync(result.bytes), rawNodes = [];
  function walk(node) { rawNodes.push(node); for (const child of node.children || node.artboard?.children || node.group?.children || node.shape?.children || []) walk(child); }
  for (const [name, bytes] of Object.entries(archive)) if (name.startsWith("artwork/") && name.endsWith(".agc")) walk(JSON.parse(strFromU8(bytes)));
  const raw = (name) => rawNodes.find((node) => node.name === name);
  assert.ok(archive[`resources/${hash}`], "original image bytes remain embedded");
  assert.deepEqual(archive[`resources/${hash}`], graph.images.get(hash));
  assert.equal(raw("Gradient mask / 原始图层备份（隐藏）").visible, false);
  assert.equal(raw("Gradient mask").meta.ux.orbitSourceProperties.maskType, "ALPHA");
  assert.equal(raw("Spread shadow").meta.ux.orbitSourceProperties.effects[0].spread, 5);
  assert.equal(raw("Spread shadow / 原始效果备份（隐藏）").visible, false);
  assert.equal(raw("Gradient text / 原始文字备份（隐藏）").type, "text");
  assert.equal(raw("Gradient text / 原始文字备份（隐藏）").visible, false);
  assert.equal(raw("Gradient text / 渐变文字矢量外观").shape.type, "path");
  assert.match(raw("Gradient text / 渐变文字矢量外观").shape.path, /^M/);
  assert.ok(raw("Gradient text / 渐变文字矢量外观").shape.path.length > 20);
  assert.equal(raw("Gradient text / 渐变文字矢量外观").style.fill.type, "gradient");
  assert.equal(raw("Gradient text / 渐变文字矢量外观").style.fill.gradient.units, "objectBoundingBox");
  assert.equal(raw("Gradient text / 渐变文字矢量外观").style.fill.gradient.y2, 1.25);
  assert.equal(raw("Gradient text / 渐变文字矢量外观").visible, true);
  assert.deepEqual(raw("Gradient text / 渐变文字矢量外观").transform, { a: 1, b: 0, c: 0, d: 1, tx: 0, ty: 0 });
  assert.ok((await readDesign(result.bytes, result.filename)).graph.nodes.size > graph.nodes.size);
  const saved = mask.maskType; mask.maskType = "LUMINANCE";
  await assert.rejects(convertDesign(parsed, "xd", options), (error) => error.code === "PRESERVATION_REQUIRED");
  mask.maskType = saved;
  const glyphs = text.derivedTextGlyphs; text.derivedTextGlyphs = null;
  await assert.rejects(convertDesign(parsed, "xd", options), (error) => error.code === "PRESERVATION_REQUIRED");
  text.derivedTextGlyphs = [{ ...glyphs[0], commandsBlob: Uint8Array.of(0) }];
  await assert.rejects(convertDesign(parsed, "xd", options), /无有效轮廓/);
  text.derivedTextGlyphs = glyphs;
  const radius = shadow.effects[0].radius; shadow.effects[0].radius = 1000000;
  await assert.rejects(convertDesign(parsed, "xd", options), /阴影扩展范围过大/);
  shadow.effects[0].radius = radius;
  graph.deleteNode(text.id);
  const browserFixture = await writeFigma(graph, "compatible-browser", EMPTY_PNG);
  const reread = await readDesign(browserFixture, "compatible-browser.fig");
  assert.ok(inspectDesign(reread, "xd", options).every((issue) => issue.severity === "info"));
  await fs.writeFile("/tmp/pm-workbench-compatible.xd", result.bytes);
  text.derivedTextGlyphs = glyphs;
  console.log("PASS: compatible XD export bakes alpha per image without changing originals, rebuilds spread shadows, preserves vector text appearance and hidden editable sources, and still blocks unsupported fallbacks.");
  return { bytes: browserFixture, mask, shadow };
};
